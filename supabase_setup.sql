-- Jalankan di Supabase Dashboard > SQL Editor.
-- Guestbook ini memang publik: semua tamu dapat membaca dan menambahkan ucapan.
-- Tidak ada izin update/delete untuk pengunjung anonim.

create table if not exists public.wedding_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  message text not null check (char_length(btrim(message)) between 1 and 300),
  attendance text not null check (attendance in ('Hadir', 'Berhalangan hadir', 'Masih ragu')),
  emoji text not null default '💖',
  created_at timestamptz not null default now()
);

alter table public.wedding_messages enable row level security;

-- Batasi hak akses publik hanya untuk membaca dan menambahkan ucapan.
revoke all on table public.wedding_messages from anon, authenticated;
grant select, insert on table public.wedding_messages to anon, authenticated;

drop policy if exists "Public can read wedding messages" on public.wedding_messages;
create policy "Public can read wedding messages"
  on public.wedding_messages
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can add wedding messages" on public.wedding_messages;
create policy "Public can add wedding messages"
  on public.wedding_messages
  for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 80
    and char_length(btrim(message)) between 1 and 300
    and attendance in ('Hadir', 'Berhalangan hadir', 'Masih ragu')
  );
